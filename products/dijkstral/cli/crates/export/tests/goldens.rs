//! Exporters against Graphify's own (`docs/graphify-exports.md` §5): `graphify export graphml`,
//! `export wiki` and `export html` run on each `<lang>.clustered.graphify.json`, stored under
//! `tests/fixtures/exports/<lang>/`.
//!
//! - GraphML: byte for byte.
//! - Wiki: the same files, byte for byte after naming the product (`graphify` → `dijkstral`, and
//!   the index footer's link to Graphify's repository → plain `dijkstral`).
//! - HTML: Graphify's template is not stored, only its embedded data (`html_payload.json`). Every
//!   node and link record must match, in order, with all of Graphify's keys and values; dijkstral
//!   adds `source_location` to nodes and fills `LEGEND`, which Graphify leaves empty without a
//!   labels file (quirk X2).

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use dijkstral_export::html::{self, HtmlOptions, Mode};
use dijkstral_export::{graphml, wiki, Loaded, Names};
use serde_json::{json, Value};

const LANGS: [&str; 7] = [
    "python",
    "typescript",
    "javascript",
    "rust",
    "go",
    "java",
    "mixed",
];

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures")
}

fn graph(lang: &str) -> Value {
    let path = fixtures().join(format!("{lang}.clustered.graphify.json"));
    serde_json::from_slice(&fs::read(path).unwrap()).unwrap()
}

fn golden(lang: &str) -> PathBuf {
    fixtures().join("exports").join(lang)
}

#[test]
fn graphml_matches_graphify_byte_for_byte() {
    for lang in LANGS {
        let ours = graphml::render(&graph(lang)).unwrap();
        let want = fs::read_to_string(golden(lang).join("graph.graphml")).unwrap();
        assert_eq!(ours, want, "{lang}: graph.graphml");
    }
}

/// Lines where dijkstral deliberately differs: `(lang, file, Graphify's line, ours)`.
const ALLOWED: &[(&str, &str, &str, &str)] = &[
    // Quirk W3: Graphify links every god node in the index by label, so the second of two
    // `Formatter` god nodes points at the first one's article; dijkstral links each to its own.
    (
        "java",
        "index.md",
        "- [Formatter](Formatter.md) — 3 connections",
        "- [Formatter](Formatter_2.md) — 3 connections",
    ),
];

fn allow(lang: &str, file: &str, text: &str) -> String {
    let mut text = text.to_string();
    for (l, f, theirs, ours) in ALLOWED {
        if *l == lang && *f == file {
            assert!(
                text.contains(theirs),
                "{lang}/{file}: allowed line not found"
            );
            text = text.replace(theirs, ours);
        }
    }
    text
}

fn normalise_wiki(text: &str) -> String {
    text.replace(
        "*Generated by [graphify](https://github.com/Graphify-Labs/graphify)*",
        "*Generated by dijkstral*",
    )
    .replace("graphify", "dijkstral")
}

#[test]
fn wiki_matches_graphify() {
    for lang in LANGS {
        let loaded = Loaded::from_json(&graph(lang)).unwrap();
        let view = loaded.view(Names::Placeholder);
        let ours: BTreeMap<String, String> = wiki::render(&view).unwrap().into_iter().collect();
        let dir = golden(lang).join("wiki");
        let mut want = BTreeMap::new();
        for entry in fs::read_dir(&dir).unwrap() {
            let entry = entry.unwrap();
            let name = entry.file_name().to_string_lossy().into_owned();
            let text = normalise_wiki(&fs::read_to_string(entry.path()).unwrap());
            let text = allow(lang, &name, &text);
            want.insert(name, text);
        }
        assert_eq!(
            ours.keys().collect::<Vec<_>>(),
            want.keys().collect::<Vec<_>>(),
            "{lang}: wiki file names"
        );
        for (name, text) in &want {
            assert_eq!(&ours[name], text, "{lang}: wiki/{name}");
        }
    }
}

/// The JSON a page embeds.
pub fn embedded(page: &str) -> Value {
    let open = "<script id=\"graph-data\" type=\"application/json\">";
    let start = page.find(open).expect("data element") + open.len();
    let end = start + page[start..].find("</script>").expect("end of data");
    serde_json::from_str(&page[start..end]).expect("embedded JSON")
}

#[test]
fn html_payload_matches_graphify() {
    for lang in LANGS {
        let loaded = Loaded::from_json(&graph(lang)).unwrap();
        let view = loaded.view(Names::Placeholder);
        let page = html::render(&view, &HtmlOptions::default());
        let ours = embedded(&page);
        let want: Value =
            serde_json::from_slice(&fs::read(golden(lang).join("html_payload.json")).unwrap())
                .unwrap();
        assert_eq!(ours["mode"], "vis");

        let (on, wn) = (
            ours["RAW_NODES"].as_array().unwrap(),
            want["RAW_NODES"].as_array().unwrap(),
        );
        assert_eq!(on.len(), wn.len(), "{lang}: node count");
        for (o, w) in on.iter().zip(wn) {
            for (k, v) in w.as_object().unwrap() {
                assert_eq!(&o[k], v, "{lang}: node {} field {k}", w["id"]);
            }
            let extra: Vec<&String> = o
                .as_object()
                .unwrap()
                .keys()
                .filter(|k| w.get(k.as_str()).is_none())
                .collect();
            assert!(
                extra.is_empty() || extra == ["source_location"],
                "{lang}: extra node keys {extra:?}"
            );
        }
        assert_eq!(ours["RAW_EDGES"], want["RAW_EDGES"], "{lang}: links");
        assert_eq!(ours["hyperedges"], want["hyperedges"], "{lang}: hyperedges");

        // Graphify's LEGEND is empty here (no labels file); ours lists every community.
        assert_eq!(want["LEGEND"], Value::Array(vec![]));
        let legend = ours["LEGEND"].as_array().unwrap();
        let total: u64 = legend.iter().map(|c| c["count"].as_u64().unwrap()).sum();
        assert_eq!(total as usize, on.len(), "{lang}: legend counts");
        for c in legend {
            let cid = c["cid"].as_u64().unwrap();
            assert_eq!(c["label"], format!("Community {cid}").as_str());
            assert_eq!(c["color"], html::PALETTE[cid as usize % 10]);
        }
    }
}

/// `(golden directory, multirepo golden)`: global graphs, whose links carry the true direction
/// in `_src`/`_tgt` while `source`/`target` follow NetworkX iteration order (often reversed).
const GLOBAL: [(&str, &str); 2] = [
    ("global_direction", "global_direction"),
    ("global_py_go", "global_py_go.3"),
];

fn global_graph(input: &str) -> Value {
    let path = fixtures().join(format!("multirepo/goldens/{input}.graph.json"));
    serde_json::from_slice(&fs::read(path).unwrap()).unwrap()
}

/// `graph.html` draws every link from `_src` to `_tgt`; GraphML keeps the stored `source` and
/// `target` (it writes `G.edges()` order, never the link's direction); the wiki shows no
/// direction.
#[test]
fn global_graphs_match_graphify() {
    for (golden, input) in GLOBAL {
        let doc = global_graph(input);
        let dir = fixtures().join("exports").join(golden);
        let ours = graphml::render(&doc).unwrap();
        let want = fs::read_to_string(dir.join("graph.graphml")).unwrap();
        assert_eq!(ours, want, "{golden}: graph.graphml");

        let loaded = Loaded::from_json(&doc).unwrap();
        let view = loaded.view(Names::Placeholder);
        let ours = embedded(&html::render(&view, &HtmlOptions::default()));
        let want: Value =
            serde_json::from_slice(&fs::read(dir.join("html_payload.json")).unwrap()).unwrap();
        assert_eq!(ours["RAW_EDGES"], want["RAW_EDGES"], "{golden}: links");
        // The WebGL view's links point the same way.
        let small = HtmlOptions {
            node_limit: 3,
            ..HtmlOptions::default()
        };
        let gl = embedded(&html::render(&view, &small));
        let rows = gl["edges"].as_array().unwrap();
        assert_eq!(rows.len(), want["RAW_EDGES"].as_array().unwrap().len());
        for (row, w) in rows.iter().zip(want["RAW_EDGES"].as_array().unwrap()) {
            let id = |k: usize| gl["nodes"][row[k].as_u64().unwrap() as usize][0].clone();
            assert_eq!(
                (id(0), id(1)),
                (w["from"].clone(), w["to"].clone()),
                "{golden}"
            );
        }
        let (on, wn) = (
            ours["RAW_NODES"].as_array().unwrap(),
            want["RAW_NODES"].as_array().unwrap(),
        );
        assert_eq!(on.len(), wn.len(), "{golden}: node count");
        for (o, w) in on.iter().zip(wn) {
            for (k, v) in w.as_object().unwrap() {
                assert_eq!(&o[k], v, "{golden}: node {} field {k}", w["id"]);
            }
        }

        let ours: BTreeMap<String, String> = wiki::render(&view).unwrap().into_iter().collect();
        for entry in fs::read_dir(dir.join("wiki")).unwrap() {
            let entry = entry.unwrap();
            let name = entry.file_name().to_string_lossy().into_owned();
            // Quirk W3: two `User` god nodes from different repositories are both linked to
            // `User.md` in Graphify's index.
            if golden == "global_py_go" && name == "index.md" {
                continue;
            }
            let text = normalise_wiki(&fs::read_to_string(entry.path()).unwrap());
            assert_eq!(ours[&name], text, "{golden}: wiki/{name}");
        }
    }
    // The reversed links really are reversed in the input and drawn the other way.
    let doc = global_graph("global_direction");
    let link = &doc["links"][0];
    assert_eq!(
        (&link["source"], &link["target"]),
        (&json!("dirt::b"), &json!("dirt::a"))
    );
    let loaded = Loaded::from_json(&doc).unwrap();
    let page = html::render(&loaded.view(Names::Placeholder), &HtmlOptions::default());
    let edge = &embedded(&page)["RAW_EDGES"][0];
    assert_eq!(
        (&edge["from"], &edge["to"]),
        (&json!("dirt::a"), &json!("dirt::b"))
    );
}

/// Above the node limit the same records are embedded column-wise; expanding them gives back
/// the per-item form exactly.
#[test]
fn webgl_columns_expand_to_the_same_records() {
    for lang in LANGS {
        let loaded = Loaded::from_json(&graph(lang)).unwrap();
        let view = loaded.view(Names::Placeholder);
        let opts = HtmlOptions::default();
        let vis: Value = serde_json::from_str(&html::payload(&view, &opts, Mode::Vis)).unwrap();
        let small = HtmlOptions {
            node_limit: 3,
            ..HtmlOptions::default()
        };
        assert_eq!(html::mode(&view, &small), Mode::WebGl);
        let page = html::render(&view, &small);
        assert!(page.contains("sigma@3.0.2") && !page.contains("vis-network@"));
        let gl = embedded(&page);
        assert_eq!(gl["mode"], "webgl");
        assert_eq!(gl["LEGEND"], vis["LEGEND"]);

        let fields: Vec<&str> = gl["nodeFields"]
            .as_array()
            .unwrap()
            .iter()
            .map(|f| f.as_str().unwrap())
            .collect();
        let rows = gl["nodes"].as_array().unwrap();
        let max = rows
            .iter()
            .map(|r| r[5].as_u64().unwrap())
            .max()
            .unwrap()
            .max(1) as u32;
        let ids: Vec<&str> = rows.iter().map(|r| r[0].as_str().unwrap()).collect();
        for (r, want) in rows.iter().zip(vis["RAW_NODES"].as_array().unwrap()) {
            let get = |name: &str| &r[fields.iter().position(|f| *f == name).unwrap()];
            for name in [
                "id",
                "label",
                "community",
                "source_file",
                "file_type",
                "degree",
            ] {
                assert_eq!(get(name), &want[name], "{lang}: {name}");
            }
            assert_eq!(
                get("source_location"),
                want.get("source_location").unwrap_or(&Value::Null)
            );
            let deg = get("degree").as_u64().unwrap() as u32;
            assert_eq!(
                want["size"].as_f64().unwrap(),
                html::node_size(deg, max).parse::<f64>().unwrap()
            );
            assert_eq!(
                want["font"]["size"],
                if html::shows_label(deg, max) { 12 } else { 0 }
            );
        }
        let relations = gl["relations"].as_array().unwrap();
        let confidences = gl["confidences"].as_array().unwrap();
        let edges = gl["edges"].as_array().unwrap();
        let want_edges = vis["RAW_EDGES"].as_array().unwrap();
        assert_eq!(edges.len(), want_edges.len());
        for (e, w) in edges.iter().zip(want_edges) {
            assert_eq!(ids[e[0].as_u64().unwrap() as usize], w["from"]);
            assert_eq!(ids[e[1].as_u64().unwrap() as usize], w["to"]);
            assert_eq!(relations[e[2].as_u64().unwrap() as usize], w["label"]);
            assert_eq!(
                confidences[e[3].as_u64().unwrap() as usize],
                w["confidence"]
            );
        }
    }
}
