//! `cypher.txt` against Graphify's own (`docs/graphify-exports.md` §10): `graphify export neo4j`
//! (identical to `export falkordb`) on each fixture in `tests/fixtures/exports/<lang>/cypher.txt`
//! and on the probe graphs in `tests/fixtures/exports/probes/` (hostile strings, label and type
//! naming, the four NetworkX graph kinds, no edges, no nodes). Byte for byte after the first
//! line, which names the product.

use std::fs;
use std::path::{Path, PathBuf};

use dijkstral_export::cypher::{self, push_plan, Prop};
use dijkstral_export::nx::NxGraph;
use serde_json::{json, Value};

const LANGS: [&str; 7] = [
    "python",
    "typescript",
    "javascript",
    "rust",
    "go",
    "java",
    "mixed",
];

const PROBES: [&str; 9] = [
    "hostile",
    "names",
    "multigraph",
    "directed",
    "digraph",
    "graph",
    "noedge",
    "empty",
    "direction",
];

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../tests/fixtures")
}

fn load(path: &Path) -> NxGraph {
    NxGraph::from_json(serde_json::from_slice(&fs::read(path).unwrap()).unwrap()).unwrap()
}

fn after_header(text: &str) -> &str {
    text.split_once('\n').map_or("", |(_, rest)| rest)
}

fn check(graph: &Path, golden: &Path) {
    let ours = cypher::render(&load(graph));
    let want = fs::read_to_string(golden).unwrap();
    assert!(want.starts_with("// Neo4j Cypher import - generated by /graphify\n"));
    assert!(ours.starts_with(cypher::HEADER));
    assert_eq!(
        after_header(&ours),
        after_header(&want),
        "{}",
        golden.display()
    );
}

#[test]
fn cypher_matches_graphify_on_fixtures() {
    for lang in LANGS {
        check(
            &fixtures().join(format!("graphs-0.9.86/{lang}.clustered.graphify.json")),
            &fixtures().join("exports").join(lang).join("cypher.txt"),
        );
    }
}

#[test]
fn cypher_matches_graphify_on_probes() {
    let dir = fixtures().join("exports/probes");
    for p in PROBES {
        check(
            &dir.join(format!("{p}.graph.json")),
            &dir.join(format!("{p}.cypher.txt")),
        );
    }
}

/// Global graphs: links carry `_src`/`_tgt` and their `source`/`target` are often reversed
/// (`global_direction`: 2 of 3, `global_py_go.3`: 119 of 247); Graphify matches `_src` → `_tgt`.
#[test]
fn cypher_matches_graphify_on_global_graphs() {
    for (golden, input) in [
        ("global_direction", "global_direction"),
        ("global_py_go", "global_py_go.3"),
    ] {
        check(
            &fixtures().join(format!("multirepo/goldens/{input}.graph.json")),
            &fixtures().join(format!("exports/{golden}/cypher.txt")),
        );
    }
}

/// The push loads the same relationships as `cypher.txt`, in the true direction.
#[test]
fn push_plan_follows_the_true_direction() {
    let g = load(&fixtures().join("multirepo/goldens/global_direction.graph.json"));
    let plan = push_plan(&g);
    let mut edges: Vec<(String, String, String)> = plan
        .edges
        .iter()
        .flat_map(|((_, ty, _), es)| {
            es.iter()
                .map(move |e| (e.source.clone(), ty.clone(), e.target.clone()))
        })
        .collect();
    edges.sort();
    let want = [
        ("dirt::a", "CALLS", "dirt::b"),
        ("dirt::s1", "ST", "dirt::s2"),
        ("stubs::f", "REF", "dirt::s1"),
    ];
    assert_eq!(
        edges,
        want.map(|(s, t, d)| (s.to_string(), t.to_string(), d.to_string()))
    );
    // Batches are keyed by the labels of the true source and target.
    assert!(plan
        .edges
        .contains_key(&("Entity".into(), "REF".into(), "Entity".into())));
}

/// The body of a single-quoted Cypher string starting at `s[0]`, and the rest after the closing
/// quote; `None` if it is not closed.
fn literal(s: &str) -> Option<(String, &str)> {
    let mut out = String::new();
    let mut chars = s.char_indices();
    while let Some((i, c)) = chars.next() {
        match c {
            '\\' => match chars.next()?.1 {
                '\\' => out.push('\\'),
                '\'' => out.push('\''),
                _ => return None, // only these two escapes are ever written
            },
            '\'' => return Some((out, &s[i + 1..])),
            c => out.push(c),
        }
    }
    None
}

const HOSTILE: [&str; 9] = [
    "'}); MATCH (n) DETACH DELETE n //",
    "\\'}) DETACH DELETE n //",
    "it's \"q\" \\ \\\\'",
    "line\nbreak\r\u{0}\u{1b}[31m",
    "`backtick`) MERGE (x:Evil",
    "\u{2028}\u{2029}\u{feff}漢字",
    "\\u0027 \\x27 \\",
    "*/ /* -- ;",
    "$param {x}",
];

fn hostile_graph() -> Value {
    let nodes: Vec<Value> = HOSTILE
        .iter()
        .enumerate()
        .map(|(i, s)| json!({"id": format!("{s}#{i}"), "label": s, "file_type": s}))
        .collect();
    let links: Vec<Value> = (1..HOSTILE.len())
        .map(|i| {
            json!({"source": format!("{}#{}", HOSTILE[i - 1], i - 1),
                   "target": format!("{}#{i}", HOSTILE[i]),
                   "relation": HOSTILE[i], "confidence": HOSTILE[i - 1]})
        })
        .collect();
    json!({"directed": false, "multigraph": false, "nodes": nodes, "links": links})
}

/// Every statement keeps its shape whatever the strings hold: each line parses back to exactly
/// the expected statement with the strings Graphify's escaping keeps (control characters but
/// tab removed).
#[test]
fn hostile_strings_stay_literals() {
    let g = NxGraph::from_json(hostile_graph()).unwrap();
    let text = cypher::render(&g);
    let clean = |s: &str| -> String { s.chars().filter(|&c| c >= ' ' || c == '\t').collect() };
    let lines: Vec<&str> = text.lines().collect();
    assert_eq!(lines.len(), 2 + HOSTILE.len() + 1 + HOSTILE.len() - 1);
    for (i, s) in HOSTILE.iter().enumerate() {
        let line = lines[2 + i];
        let rest = line.strip_prefix("MERGE (n:").unwrap();
        let (label, rest) = rest.split_once(" {id: '").unwrap();
        assert!(label.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'));
        let (id, rest) = literal(rest).unwrap();
        assert_eq!(id, clean(&format!("{s}#{i}")));
        let rest = rest.strip_prefix(", label: '").unwrap();
        let (l, rest) = literal(rest).unwrap();
        assert_eq!(l, clean(s));
        assert_eq!(rest, "});");
    }
    for (k, line) in lines[3 + HOSTILE.len()..].iter().enumerate() {
        let i = k + 1;
        let rest = line.strip_prefix("MATCH (a {id: '").unwrap();
        let (a, rest) = literal(rest).unwrap();
        assert_eq!(a, clean(&format!("{}#{}", HOSTILE[i - 1], i - 1)));
        let rest = rest.strip_prefix("}), (b {id: '").unwrap();
        let (b, rest) = literal(rest).unwrap();
        assert_eq!(b, clean(&format!("{}#{i}", HOSTILE[i])));
        let rest = rest.strip_prefix("}) MERGE (a)-[:").unwrap();
        let (ty, rest) = rest.split_once(" {confidence: '").unwrap();
        assert!(ty.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'));
        let (conf, rest) = literal(rest).unwrap();
        assert_eq!(conf, clean(HOSTILE[i - 1]));
        assert_eq!(rest, "}]->(b);");
    }
}

#[test]
fn push_records_keep_hostile_strings_as_data() {
    let g = NxGraph::from_json(hostile_graph()).unwrap();
    let plan = push_plan(&g);
    assert_eq!(plan.node_count, HOSTILE.len());
    for label in &plan.labels {
        assert!(!label.is_empty());
        assert!(label.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'));
    }
    for (s, ty, t) in plan.edges.keys() {
        for name in [s, ty, t] {
            assert!(name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'));
        }
    }
    // The values themselves travel unchanged (as Bolt parameters or escaped FalkorDB literals).
    let ids: Vec<&str> = plan
        .nodes
        .values()
        .flatten()
        .map(|n| n.id.as_str())
        .collect();
    for (i, s) in HOSTILE.iter().enumerate() {
        assert!(ids.contains(&format!("{s}#{i}").as_str()));
    }
    let node = plan.nodes.values().flatten().next().unwrap();
    assert!(matches!(node.props.last(), Some((k, Prop::Str(_))) if k == "id"));
}

#[test]
fn push_plan_groups_are_deterministic() {
    let g = load(&fixtures().join("graphs-0.9.86/python.clustered.graphify.json"));
    let a = push_plan(&g);
    let b = push_plan(&g);
    let shape = |p: &cypher::PushPlan| {
        p.edges
            .iter()
            .map(|(k, v)| {
                (
                    k.clone(),
                    v.iter().map(|e| e.source.clone()).collect::<Vec<_>>(),
                )
            })
            .collect::<Vec<_>>()
    };
    assert_eq!(shape(&a), shape(&b));
    assert_eq!(a.labels, ["Code", "Concept", "Rationale"]);
    assert_eq!(a.edge_count, 107);
    assert_eq!(cypher::render(&g), cypher::render(&g));
}
